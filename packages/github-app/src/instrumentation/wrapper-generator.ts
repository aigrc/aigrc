import type { DetectionResult } from "@aigrc/core";
import type { InstrumentationOutput, RiskTier, TierLabel } from "../types.js";

/**
 * Generate a governance wrapper for a specific framework.
 */
export function generateWrapper(
  frameworkId: string,
  detection: DetectionResult,
  tier: RiskTier,
  tierLabel: TierLabel
): InstrumentationOutput | null {
  const generator = GENERATORS[frameworkId];
  if (!generator) return null;

  return generator(detection, tier, tierLabel);
}

// ─────────────────────────────────────────────────────────────────
// GENERATOR REGISTRY
// ─────────────────────────────────────────────────────────────────

type WrapperGenerator = (
  detection: DetectionResult,
  tier: RiskTier,
  tierLabel: TierLabel
) => InstrumentationOutput;

const GENERATORS: Record<string, WrapperGenerator> = {
  "openai": generateOpenAiWrapper,
  "anthropic-sdk": generateAnthropicWrapper,
  "langchain": generateLangchainWrapper,
  "crewai": generateCrewAiWrapper,
  "vercel-ai-sdk": generateVercelAiWrapper,
  "pydantic-ai": generatePydanticAiWrapper,
  "mcp-sdk-ts": generateMcpTsWrapper,
  "mcp-sdk-py": generateMcpPyWrapper,
  "fastmcp": generateFastMcpWrapper,
  "mastra": generateMastraWrapper,
};

