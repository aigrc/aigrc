// ─────────────────────────────────────────────────────────────────
// PangoGuard — Auto-Instrumentation Engine
// Generates opt-out governance wrappers for detected frameworks
// ─────────────────────────────────────────────────────────────────

import type { DetectionResult } from "@aigrc/core";
import type { InstrumentationOutput, AppScanResult } from "../types.js";
import { generateWrapper } from "./wrapper-generator.js";
import { createLogger } from "../utils/logger.js";

const log = createLogger("instrumentor");

/**
 * Supported frameworks for auto-instrumentation.
 * Each maps to a template that generates a governed wrapper file.
 */
export const SUPPORTED_FRAMEWORKS = new Set([
  "openai",
  "anthropic-sdk",
  "langchain",
  "crewai",
  "vercel-ai-sdk",
  "pydantic-ai",
  "mcp-sdk-ts",
  "mcp-sdk-py",
  "fastmcp",
  "mastra",
]);

/**
 * Generate auto-instrumentation wrapper files for detected frameworks.
 *
 * Auto-instrumentation is OPT-OUT: wrappers are generated by default
 * and suggested in the PR comment. Developers can disable via .aigrc.yaml.
 *
 * @param result - Full scan result with detections
 * @returns Array of generated instrumentation outputs
 */
export function generateInstrumentation(
  result: AppScanResult
): InstrumentationOutput[] {
  const outputs: InstrumentationOutput[] = [];
  const processedFrameworks = new Set<string>();

  for (const detection of result.scanResult.detections) {
    // Only instrument supported frameworks, one wrapper per framework
    const frameworkId = getFrameworkId(detection);
    if (!frameworkId || !SUPPORTED_FRAMEWORKS.has(frameworkId)) continue;
    if (processedFrameworks.has(frameworkId)) continue;
    processedFrameworks.add(frameworkId);

    try {
      const output = generateWrapper(
        frameworkId,
        detection,
        result.tier,
        result.tierLabel
      );

      if (output) {
        outputs.push(output);
        log.info(`Generated wrapper for ${frameworkId}`, {
          filePath: output.filePath,
          language: output.language,
        });
      }
    } catch (error) {
      log.warn(`Failed to generate wrapper for ${frameworkId}`, {
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  log.info(`Generated ${outputs.length} instrumentation wrappers`);
  return outputs;
}

/**
 * Map a detection result to a framework ID for instrumentation lookup.
 */
function getFrameworkId(detection: DetectionResult): string | null {
  // Direct match on detection framework field
  const framework = detection.framework.toLowerCase();

  // Map common framework names to instrumentation IDs
  const frameworkMap: Record<string, string> = {
    "openai": "openai",
    "openai sdk": "openai",
    "anthropic": "anthropic-sdk",
    "anthropic sdk": "anthropic-sdk",
    "langchain": "langchain",
    "crewai": "crewai",
    "vercel ai sdk": "vercel-ai-sdk",
    "pydantic ai": "pydantic-ai",
    "mcp sdk (typescript)": "mcp-sdk-ts",
    "mcp sdk (python)": "mcp-sdk-py",
    "fastmcp": "fastmcp",
    "mastra": "mastra",
  };

  return frameworkMap[framework] ?? null;
}
